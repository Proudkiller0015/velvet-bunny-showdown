'use strict';
/**
 * Give Samantha every move in the game.
 *
 * Generated rather than written out, because "every move" is a moving target:
 * the list changes whenever the package is upgraded, and a hand-written copy
 * would quietly go stale and start refusing moves that exist.
 *
 * Custom Game validates neither learnsets nor legality, so she could use
 * anything regardless - but the teambuilder offers what the learnset lists, and
 * a Pokemon that can only be given moves by typing them from memory is not much
 * use to anybody.
 *
 *   node scripts/build-velvet-learnset.js
 */

const fs = require('fs');
const path = require('path');

const { Dex } = require('pokemon-showdown');

const dex = Dex.mod('gen9');
const moves = [];
for (const move of dex.moves.all()) {
	if (!move.exists) continue;
	// Z-moves and Max moves are not chosen in the builder; they come from an item
	// or from Dynamax, and listing them would fill the box with things that do
	// nothing when clicked.
	if (move.isZ || move.isMax) continue;
	if (move.isNonstandard && move.isNonstandard !== 'Past') continue;
	moves.push(move.id);
}
// Her own move is not in the package's dex, so it has to be added by hand.
for (const own of ['queenbeam', 'queensdance', 'queensheal']) moves.push(own);
moves.sort();

const learnset = {};
// '9M' is the ninth generation's TM source - the one the validator is happiest
// with, and the one that reads as "she can just do this".
for (const id of moves) learnset[id] = ['9M'];

const out = path.join(__dirname, '..', 'data', 'velvet', 'learnsets.js');
const body = [
	"'use strict';",
	'/**',
	' * Samantha learns everything.',
	' *',
	' * Generated by scripts/build-velvet-learnset.js from the dex in the installed',
	" * package - do not edit by hand, and re-run it after upgrading Showdown so the",
	' * list picks up whatever was added.',
	' *',
	` * ${moves.length} moves, as of this build.`,
	' */',
	'',
	'exports.Learnsets = {',
	'\tsamantha: {',
	'\t\tlearnset: {',
	...moves.map(id => `\t\t\t${id}: ['9M'],`),
	'\t\t},',
	'\t},',
	'};',
	'',
].join('\n');

fs.mkdirSync(path.dirname(out), { recursive: true });
fs.writeFileSync(out, body);
console.log(`wrote ${path.relative(path.join(__dirname, '..'), out)} with ${moves.length} moves`);
