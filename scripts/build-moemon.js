'use strict';
/**
 * Moemon sprites: the Moemon Project's sprite database, as alternative looks players
 * pick in the builder ("Change sprite"). Used with the Project's permission (asked by
 * the owner, 28 Oct 2026); credited in the public Moemon room (config/showdown-config.js).
 *
 * Input: the frames cut from the database's spritesets (front, shiny front, back, shiny
 * back, 64x64 each) as client/sprites/moemon/m<row>*.png, and the rows they came from
 * (rows.json: species, form, repo name, artist), both made by tools/moemon/ from the
 * database's .xlsx export.
 *
 *   node scripts/build-moemon.js <rows.json>
 *
 * Writes client/js/velvet-moemon.js (Pokemon id -> its variants, in database order) and
 * data/moemon-credits.json (artists, for the room).
 */

const fs = require('fs');
const path = require('path');
const { Dex } = require('pokemon-showdown');

const ROOT = path.join(__dirname, '..');
const rows = JSON.parse(fs.readFileSync(process.argv[2], 'utf8'));
const dex = Dex.forFormat(Dex.formats.get('gen9rpag'));
const have = new Set(fs.readdirSync(path.join(ROOT, 'client', 'sprites', 'moemon')));

// The database's form names, as Showdown spells them.
const FORM = {
	'Mega': 'Mega', 'Mega X': 'Mega-X', 'Mega Y': 'Mega-Y', 'Mega Z': 'Mega-Z', 'Alolan': 'Alola', 'Galarian': 'Galar',
	'Hisuian': 'Hisui', 'Paldean': 'Paldea', 'Gigantamax': 'Gmax', 'Primal': 'Primal',
};
// Pokemon whose formes change in battle on their own (Gourgeist's size): one list for all.
const ONE_LIST = ['gourgeist', 'pumpkaboo'];

const variants = {};
const artists = new Map();
for (let i = 0; i < rows.length; i++) {
	const r = rows[i];
	if (!have.has(`m${i}.png`)) continue;
	const base = dex.species.get(r.species);
	if (!base.exists) continue;
	const form = String(r.form || '').trim();
	let id = base.id;
	if (form && !ONE_LIST.includes(toID(base.baseSpecies))) {
		const formed = dex.species.get(`${base.baseSpecies}-${FORM[form] || form}`);
		if (formed.exists && formed.baseSpecies === base.baseSpecies) id = formed.id;
	}
	if (ONE_LIST.includes(toID(base.baseSpecies))) id = toID(base.baseSpecies);
	const by = String(r.by || '').trim();
	const label = [form && !dex.species.get(`${base.baseSpecies}-${FORM[form] || form}`).exists ? form : '', by ? `by ${by}` : ''].filter(Boolean).join(', ');
	(variants[id] = variants[id] || []).push([`m${i}`, label]);
	for (const name of [by, String(r.edited || '').trim()].join(' / ').split(/\s*[/,&]\s*|\s+and\s+|\s*-\s+/)) {
		const n = name.replace(/^(Front|Back|Shiny|Edit(ed)?( by)?)\s*:?\s*/i, '').trim();
		if (n && n.length < 40) artists.set(n.toLowerCase(), n);
	}
}
function toID(s) { return String(s || '').toLowerCase().replace(/[^a-z0-9]+/g, ''); }

const count = Object.values(variants).reduce((t, l) => t + l.length, 0);
fs.writeFileSync(path.join(ROOT, 'client', 'js', 'velvet-moemon.js'), `/**
 * Moemon sprites: the Moemon Project's sprite database (with its permission; credited in
 * the Moemon room). Pokemon id -> [file, label] per variant, in the database's order;
 * a set picks one with \`pokeball: 'Moemon N'\` (client/js/velvet-data.js, MOEMON).
 *
 * Generated by scripts/build-moemon.js - do not edit by hand.
 */
window.VelvetMoemon = ${JSON.stringify(variants)};
`);
const credits = [...artists.values()].sort((a, b) => a.localeCompare(b));
fs.writeFileSync(path.join(ROOT, 'data', 'moemon-credits.json'), JSON.stringify({ built: new Date().toISOString().slice(0, 10), pokemon: Object.keys(variants).length, sprites: count, artists: credits }, null, 1));
console.log(`${count} sprites for ${Object.keys(variants).length} Pokemon, ${credits.length} artists`);
