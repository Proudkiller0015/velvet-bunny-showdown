'use strict';
/**
 * Our custom data, in the shape Showdex's damage calculator expects.
 *
 *   node scripts/build-calc-data.js
 *
 * Showdex does its maths with @smogon/calc, which carries its own copies of
 * every Pokemon, move, ability and item - nothing to do with the client's dex,
 * and nothing to do with ours. Its dropdowns come from the client (so our
 * things are listed), and its numbers come from those bundled tables (so our
 * things mean nothing to them). A Samantha in the calculator was an unknown
 * species.
 *
 * The good news is that the Z-A Megas are already in there, so the 49 of them
 * calculate correctly without us. What is missing is only what we invented.
 *
 * What this can and cannot fix, plainly:
 *
 *   - a species is data, so Samantha's stats and types come out right
 *   - a move is data, so base power, type and category come out right
 *   - an ability or item is only a NAME to the calculator; what it does lives
 *     in the damage formula, which we are not patching. So Verdant Surge and
 *     the Elemental Banana are accepted and ignored rather than accepted and
 *     applied. Being known is still better than being unknown, which is the
 *     difference between a number that is slightly low and no number at all.
 */

const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const PACKAGE = path.join(ROOT, 'node_modules', 'pokemon-showdown');
const OUT = path.join(ROOT, 'client', 'js', 'velvet-calc-data.js');

// RP's data (the gen9rp mod): the base dex is Showdown's own and has none of ours.
const Dex = require(path.join(PACKAGE, 'dist', 'sim', 'dex.js')).Dex.mod('gen9rp');

/** Everything this server invented, as opposed to everything it changed. */
// Banette-Mega-Halloween (24 Sep 2026): the Halloween 2026 Mega, Ghost/Dark. The
// calculator knows Mega Banette, but not this one's stats or second type.
const SPECIES = ['samantha', 'nuzleafsold', 'banettemegahalloween'];
/*
 * Moves and abilities are worked out rather than listed: anything with a
 * negative number is ours. A hand-written list is how Balance Patch 1's eleven
 * moves and Colossus Unbound nearly shipped to the server and not to the
 * calculator.
 */
// Smogon's CAP Pokemon number theirs negatively too; those are not ours.
const MOVES = Dex.moves.all().filter(m => m.exists && m.num < 0 && m.isNonstandard !== 'CAP').map(m => m.id);
const ABILITIES = Dex.abilities.all().filter(a => a.exists && a.num < 0 && a.isNonstandard !== 'CAP').map(a => a.id);
// Banettite-Halloween (24 Sep 2026): its stone, so a set holding it is not refused.
const ITEMS = ['elementalbanana', 'brokenpact', 'banettitehalloween'];

/**
 * The calculator's own field names, which are not Showdown's.
 *
 * Stats are `bs` with two-letter keys. A move's category is always written:
 * the calculator's data leaves it out for Special moves, but a move added
 * without one comes out as a Status move there, and every special move of ours
 * (Oxidize, the lake trio's, Great Sage Strike...) calculated 0 damage.
 */
function speciesRow(species) {
	return {
		types: species.types.slice(),
		bs: {
			hp: species.baseStats.hp,
			at: species.baseStats.atk,
			df: species.baseStats.def,
			sa: species.baseStats.spa,
			sd: species.baseStats.spd,
			sp: species.baseStats.spe,
		},
		weightkg: species.weightkg,
	};
}

function moveRow(move) {
	const row = { bp: move.basePower, type: move.type };
	row.category = move.category;
	if (move.priority) row.priority = move.priority;
	if (move.flags && move.flags.contact) row.makesContact = true;
	if (move.drain) row.drain = move.drain;
	if (move.recoil) row.recoil = move.recoil;
	if (move.multihit) row.multihit = move.multihit;
	return row;
}

const species = {};
for (const id of SPECIES) {
	const found = Dex.species.get(id);
	if (!found.exists) throw new Error(`${id} is not a species`);
	species[found.name] = speciesRow(found);
}

// Species this server changed (types, stats): written over the calculator's own rows.
const { CHANGED } = require(path.join(PACKAGE, 'dist', 'data', 'velvet', 'unnerfs.js'));
const changedSpecies = {};
for (const id of CHANGED.species || []) {
	const found = Dex.species.get(id);
	if (found.exists) changedSpecies[found.name] = speciesRow(found);
}

const moves = {};
for (const id of MOVES) {
	const found = Dex.moves.get(id);
	if (!found.exists) throw new Error(`${id} is not a move`);
	moves[found.name] = moveRow(found);
}

const abilities = ABILITIES.map(id => {
	const found = Dex.abilities.get(id);
	if (!found.exists) throw new Error(`${id} is not an ability`);
	return found.name;
});

const items = ITEMS.map(id => {
	const found = Dex.items.get(id);
	if (!found.exists) throw new Error(`${id} is not an item`);
	return found.name;
});

const file = `/**
 * Our custom data, for Showdex's damage calculator.
 *
 * Generated by scripts/build-calc-data.js - do not edit by hand.
 *
 * Loaded before /showdex/main.js, which is patched to read this on the way up
 * (see scripts/patch-showdex.js). Abilities and items are names only: the
 * calculator implements what they do in its own damage formula, which we do not
 * touch, so ours are accepted and ignored rather than accepted and applied.
 */
window.__VELVET_CALC_DATA = {
\tspecies: ${JSON.stringify(species)},
\tchangedSpecies: ${JSON.stringify(changedSpecies)},
\tmoves: ${JSON.stringify(moves)},
\tabilities: ${JSON.stringify(abilities)},
\titems: ${JSON.stringify(items)},
};
`;

fs.writeFileSync(OUT, file);
console.log(`${Object.keys(species).length} species, ${Object.keys(moves).length} moves, ` +
	`${abilities.length} abilities, ${items.length} items -> ${OUT}`);
console.log('  species:', Object.keys(species).join(', '));
console.log('  moves:  ', Object.keys(moves).join(', '));
