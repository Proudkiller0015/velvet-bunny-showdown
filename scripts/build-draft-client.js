'use strict';

/*
 * The draft pool for the teambuilder: client/js/velvet-draft.js.
 *
 * Generated from data/velvet/draft-s1.json (the draft sheet's generator writes
 * that). The builder lists, for [Gen 9] RP Draft, only the Pokemon in the pool,
 * under their draft price tier - the viability ranking coaches prep with.
 */

const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const pool = require(path.join(ROOT, 'data', 'velvet', 'draft-s1.json'));
const ORDER = ['S+', 'S', 'A+', 'A', 'B+', 'B', 'C+', 'C', 'D', 'E', 'F', 'NFE', 'LC'];

const tiers = ORDER.map(tier => {
	const list = pool.pokemon.filter(p => p.tier === tier);
	return list.length ? { tier, price: list[0].price, ids: list.map(p => p.id) } : null;
}).filter(Boolean);

const out = `/**
 * The Kagura Draft League's Season 1 pool, for the teambuilder.
 *
 * Generated by scripts/build-draft-client.js from data/velvet/draft-s1.json - do not edit by hand.
 */
window.VelvetDraft = ${JSON.stringify({ formats: ['gen9rpdraft'], season: 'Season 1', tiers }, null, '\t')};
`;
fs.writeFileSync(path.join(ROOT, 'client', 'js', 'velvet-draft.js'), out);
console.log(`velvet-draft.js: ${tiers.reduce((n, t) => n + t.ids.length, 0)} Pokemon in ${tiers.length} tiers`);
