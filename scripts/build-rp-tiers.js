'use strict';
/**
 * Every Pokemon's RP tier, as the RP ladders enforce it, for the RP bot.
 *
 *   node scripts/build-rp-tiers.js     -> src/rp-tiers.json (+ a copy into ../rp-bot/src/pokemon/)
 *
 * The RP bot's rarity (src/rarity.js, copied there) cannot load this server's
 * patched dex, so it went on reading Smogon's tiers and no tier shift ever
 * reached rarity (the owner, 30 Sep 2026). The tier is the tier sim's pool
 * reading (src/tier-sim/pool.js currentTier = config/custom-formats.js lowTierOf).
 * Run it after changing data/velvet/tiering.js, then `npm run setup`.
 */
const fs = require('fs');
const path = require('path');

const dex = require('../src/rp-dex')();
const { buildPool } = require('../src/tier-sim/pool');

const out = {};
for (const e of buildPool(dex, { includeNfe: false })) out[e.id] = e.tier;
// Collab (data/velvet/collab.js): above AG, never tiered by the pool, and legal only in RP Collab.
for (const id of require('pokemon-showdown/dist/data/velvet/collab.js').SPECIES) out[id] = 'Collab';
// Touhou (data/velvet/touhou.js): the top of the ladder, legal only in RP Touhou and the RP Battle formats.
// Every forme a player can pick too (Cirno-Tanned, Hecatia-Earth...), not the battle-only ones.
{
	const touhou = require('pokemon-showdown/dist/data/velvet/touhou.js');
	for (const id of [...touhou.SPECIES, ...touhou.FORMES]) if (!dex.species.get(id).battleOnly) out[id] = 'Touhou';
}
const json = JSON.stringify(out, Object.keys(out).sort(), 0);
const here = path.join(__dirname, '..', 'src', 'rp-tiers.json');
fs.writeFileSync(here, json + '\n');
const bot = path.join(__dirname, '..', '..', 'rp-bot', 'src', 'pokemon', 'rp-tiers.json');
// RP_TIERS_NO_BOT=1 leaves the RP bot's copy alone (a build from a worktree, before merging).
const toBot = !process.env.RP_TIERS_NO_BOT && fs.existsSync(path.dirname(bot));
if (toBot) fs.writeFileSync(bot, json + '\n');
/*
 * And the teambuilder (client/js/velvet-data.js installRpTierHeadings), from the same
 * table the validator enforces. Before 15 Oct 2026 the builder pieced its headings
 * together from Smogon's National Dex tiers plus our own exceptions, and 240 Pokemon
 * read a tier they could not be used in (MissingNo. as RU after it became Uber).
 */
const client = path.join(__dirname, '..', 'client', 'js', 'velvet-rp-tiers.js');
fs.writeFileSync(client, '/* Generated by scripts/build-rp-tiers.js from src/rp-tiers.json - do not edit by hand. */\n' +
	`window.VelvetRpTiers = ${json};\n`);
console.log(`${Object.keys(out).length} RP tiers -> ${path.relative(process.cwd(), here)}${toBot ? ' and the RP bot' : ''}`);
